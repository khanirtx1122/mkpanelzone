const FORMAT = /^[A-Z0-9]{6}(-[A-Z0-9]{6}){5}$/;
const prisma = new PrismaClient();

async function main() {
  const seen = new Set();
  const valid = [];
  let badFormat = 0;
  let dupInList = 0;

  for (const raw of KEYS) {
    const key = raw.trim().toUpperCase();
    if (!FORMAT.test(key)) { badFormat++; console.error("BAD FORMAT:", key); continue; }
    if (seen.has(key)) { dupInList++; continue; }
    seen.add(key);
    valid.push(key);
  }

  const existing = await prisma.freePanelKey.findMany({
    where: { keyValue: { in: valid } },
    select: { keyValue: true },
  });
  const existingSet = new Set(existing.map((e) => e.keyValue));
  const toInsert = valid.filter((k) => !existingSet.has(k));

  let inserted = 0;
  if (toInsert.length > 0) {
    const batchId = randomBytes(6).toString("hex");
    const res = await prisma.freePanelKey.createMany({
      data: toInsert.map((keyValue) => ({
        keyValue,
        batchId,
        notes: "Owner batch — 6x6 format",
      })),
      skipDuplicates: true,
    });
    inserted = res.count;
  }

  const total = await prisma.freePanelKey.count();
  const available = await prisma.freePanelKey.count({ where: { status: "AVAILABLE" } });

  console.log(JSON.stringify({
    submitted: KEYS.length,
    badFormat,
    dupInList,
    alreadyInDb: valid.length - toInsert.length,
    inserted,
    dbTotals: { total, available },
  }, null, 2));
}

main()
  .catch((e) => { console.error(e); process.exitCode = 1; })
  .finally(() => prisma.$disconnect());
